// Optional browser regression: requires Playwright and an installed Chrome.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const os = require('node:os');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const errors = [];
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  const url = pathToFileURL(path.resolve(__dirname, '../index.html')).href;
  const action = name => page.locator(`[data-action="${name}"]`).first();
  const choice = (q, value) => page.locator(`input[data-question="${q}"][value="${value}"]`);
  const store = () => page.evaluate(() => JSON.parse(localStorage.getItem('markdown-quiz-notebook.v1')));
  async function confirm(name) {
    await action(name).click();
    await page.locator('#dialog-confirm').click();
    await page.locator(name === 'submit' ? '.result-summary' : name === 'retake' ? '[data-action="submit"]' : '#drop-zone').waitFor({ state: 'visible' });
  }
  try {
    await page.goto(url); await page.waitForLoadState('networkidle');
    assert.equal(await page.locator('.paper-item').count(), 0);
    await page.screenshot({ path: path.join(os.tmpdir(), 'quiz-home.png'), fullPage: true });
    await action('sample').click();
    assert.equal(await page.locator('.question').count(), 5);
    assert.equal(await page.locator('.answer-review').count(), 0);
    await choice('q1', 'B').check();
    await choice('q2', 'A').check();
    for (const value of ['A', 'C', 'D']) await choice('q3', value).check();
    await choice('q4', 'C').check();
    await page.reload();
    assert.equal(await choice('q1', 'B').isChecked(), true);
    assert.match(await page.locator('#progress-label').innerText(), /4 \/ 5/);
    await page.screenshot({ path: path.join(os.tmpdir(), 'quiz-answer.png'), fullPage: true });
    await action('submit').click();
    await page.getByRole('button', { name: '取消', exact: true }).click();
    assert.equal(await page.locator('.result-summary').count(), 0);
    await confirm('submit');
    assert.match(await page.locator('.result-summary').innerText(), /60/);
    let state = await store();
    assert.deepEqual([state.papers[0].result.correct, state.papers[0].result.wrong, state.papers[0].result.unanswered], [3, 2, 1]);
    assert.equal(state.papers[0].history.length, 1);
    await page.screenshot({ path: path.join(os.tmpdir(), 'quiz-result.png'), fullPage: true });
    await page.locator('#wrong-filter').check();
    assert.equal(await page.locator('.question').count(), 2);
    const downloadPromise = page.waitForEvent('download');
    await action('export').click();
    const download = await downloadPromise;
    const exported = await fs.readFile(await download.path(), 'utf8');
    assert.match(exported, /我的答案：A/);
    assert.match(exported, /我的答案：未作答/);
    assert.match(exported, /正确答案：A、C、D/);
    assert.match(exported, /AI 复盘提示/);
    assert.equal((exported.match(/^## \d+\./gm) || []).length, 2);
    await action('copy').click();
    await page.waitForFunction(() => /已复制|不允许自动复制/.test(document.querySelector('#feedback').textContent));
    assert.match(await page.locator('#feedback').innerText(), /已复制|不允许自动复制/);
    await action('retry-wrong').click();
    assert.equal(await page.locator('.question').count(), 2);
    assert.equal(await page.locator('.answer-review').count(), 0);
    assert.equal(await page.locator('.paper-item').count(), 2);
    await page.locator('.paper-item').first().click();
    await confirm('retake');
    assert.equal(await choice('q1', 'B').isChecked(), false);
    await page.locator('.history summary').click();
    await action('history').click();
    assert.match(await page.locator('.score').innerText(), /60/);
    assert.equal(await choice('q1', 'B').isDisabled(), true);
    await action('current').click();
    await choice('q1', 'A').check();
    await page.locator('#file-input').setInputFiles(path.resolve(__dirname, '../examples/示例试卷.md'));
    await page.waitForFunction(() => document.querySelector('#feedback').textContent.includes('已经导入'));
    assert.equal(await page.locator('.paper-item').count(), 2);
    assert.equal(await choice('q1', 'A').isChecked(), true);
    await page.reload();
    assert.equal(await choice('q1', 'A').isChecked(), true);
    state = await store();
    assert.equal(state.papers[0].history.length, 1);
    assert.equal(state.papers[0].history[0].result.score, 60);
    const bad = '# 错误试卷\n## 1. 问题\nA. 甲\nB. 乙';
    await page.locator('#file-input').setInputFiles({ name: 'bad.md', mimeType: 'text/markdown', buffer: Buffer.from(bad) });
    await page.waitForFunction(() => document.querySelector('#feedback').textContent.includes('导入失败'));
    assert.equal(await page.locator('.paper-item').count(), 2);
    const malicious = '# <img src=x onerror=window.injected=true>\n## 1. 单选题\n题目：`2 ** 3` 与 `__name__` <svg onload=window.injected=true>\nA. <img src=x onerror=window.injected=true>\nB. safe\n答案：A\n解析：<script>window.injected=true</script>';
    await page.locator('#file-input').setInputFiles({ name: 'safe.md', mimeType: 'text/markdown', buffer: Buffer.from(malicious) });
    await page.waitForFunction(() => document.querySelectorAll('.paper-item').length === 3);
    assert.equal(await page.evaluate(() => window.injected), undefined);
    assert.equal(await page.locator('#main img, #main svg, #main script').count(), 0);
    assert.match(await page.locator('.question-stem').innerText(), /2 \*\* 3/);
    assert.match(await page.locator('.question-stem').innerText(), /__name__/);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile should not overflow horizontally');
    await page.screenshot({ path: path.join(os.tmpdir(), 'quiz-mobile.png'), fullPage: true });
    await confirm('delete');
    assert.equal(await page.locator('.paper-item').count(), 2);
    const limited = await browser.newPage();
    await limited.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('quota', 'QuotaExceededError'); }; });
    await limited.goto(url);
    await limited.locator('[data-action="sample"]').click();
    assert.equal(await limited.locator('#storage-warning').isVisible(), true);
    assert.equal(await limited.locator('.question').count(), 5);
    await limited.close();
    assert.deepEqual(errors, []);
    console.log('PASS: file:// launch, example/import/dedup, draft restore, exact grade, unanswered confirmation, wrong filter/export/copy, retry/history, invalid input, HTML safety, mobile layout, delete and storage failure.');
    console.log('Screenshots:', path.join(os.tmpdir(), 'quiz-{home,answer,result,mobile}.png'));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
